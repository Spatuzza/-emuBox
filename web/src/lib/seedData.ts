export function createInitialInvoices(): SifenInvoice[] {
  const issuedAt = new Date(Date.now() - 1000 * 60 * 45);
  const items = [
    {
      productId: "prod-1",
      productSku: "YERBA-500",
      productName: "Yerba Mate Tradicional 500g",
      quantity: 2,
      unitPrice: 12500,
      taxRate: "IVA_10" as const,
      lineTotal: 25000,
      ivaAmount: computeItemIva(25000, "IVA_10"),
    },
    {
      productId: "prod-2",
      productSku: "ARROZ-1KG",
      productName: "Arroz Tipo 1 Bolsa 1kg",
      quantity: 1,
      unitPrice: 7500,
      taxRate: "IVA_5" as const,
      lineTotal: 7500,
      ivaAmount: computeItemIva(7500, "IVA_5"),
    },
  ];
  const totals = computeSaleTotals(items);
  const cdc = generateSifenCDC({
    emitter: INITIAL_EMITTER,
    documentNumber: 1,
    issuedAt,
  });
  const docNum = "0000001";

  return [
    {
      id: "inv-demo-1",
      saleNumber: 1,
      documentFullNumber: `${INITIAL_EMITTER.establecimiento}-${INITIAL_EMITTER.puntoExpedicion}-${docNum}`,
      cdc,
      mode: "mock",
      status: "APPROVED",
      customer: INITIAL_CUSTOMERS[1],
      paymentCondition: "CONTADO",
      paymentMethod: "QR",
      items,
      subtotalExenta: totals.subtotalExenta,
      subtotalIva5: totals.subtotalIva5,
      subtotalIva10: totals.subtotalIva10,
      totalIva5: totals.totalIva5,
      totalIva10: totals.totalIva10,
      totalAmount: totals.totalAmount,
      qrUrl: `https://ekuatia.set.gov.py/consultas-test/qr?nVersion=150&Id=${cdc}&cHashQR=MOCKDEMO`,
      xmlPreview: buildSifenXmlPreview({
        cdc,
        emitter: INITIAL_EMITTER,
        documentNumber: docNum,
        customerName: INITIAL_CUSTOMERS[1].name,
        customerDoc: `${INITIAL_CUSTOMERS[1].documentNumber}-${INITIAL_CUSTOMERS[1].dv}`,
        totalAmount: totals.totalAmount,
        totalIva10: totals.totalIva10,
        totalIva5: totals.totalIva5,
        items,
        issuedAtIso: issuedAt.toISOString(),
      }),
      sifenResponseCode: "0260",
      sifenResponseMsg: "Aprobado (Simulación local SIFEN_MODE=mock)",
      createdAt: issuedAt.toISOString(),
    },
  ];
}
